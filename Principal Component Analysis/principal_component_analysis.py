#Dimension Reduction Technique
#Variable Reduction Activity
#Unsupervised Learning Technique

# PCA IMAGE COMPRESSION
# STEP 1: IMPORT LIBRARIES
# =============================
import numpy as np
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA
from skimage import data
print("Libraries imported successfully!")

# STEP 2: LOAD SAMPLE IMAGE
# ============================================================

# Load the famous Cameraman grayscale image
image = data.camera()
image

# Convert image into floating point values
image = image.astype(float)
image

print("Original Image Shape:", image.shape)

# Display original image
plt.figure(figsize=(6,6))
plt.imshow(image, cmap='gray')
plt.title("Original Image")
plt.axis('off')
plt.show()

# STEP 3: UNDERSTAND IMAGE AS A MATRIX
# =============================================
# An image is represented using pixel values
# Each pixel contains an intensity value
print("Number of Rows:", image.shape[0])
print("Number of Columns:", image.shape[1])

print("\nFirst 5 x 5 pixel values:")
print(image[:5, :5])

# Display image as a numerical matrix
plt.figure(figsize=(6,5))
plt.imshow(image[:20, :20], cmap='gray')
plt.title("20 x 20 Pixel Region")
plt.colorbar(label="Pixel Intensity")
plt.show()

# STEP 4: UNDERSTAND PCA
# PCA identifies the most important patterns
# It reduces the number of dimensions
# Here each image row is treated as one observation
pca_full = PCA()
pca_full.fit(image)
print("PCA completed!")
print("Total Components:", pca_full.n_components_)

# STEP 5: EXPLAINED VARIANCE DIAGRAM
# Explained variance shows information captured
# by each principal component
plt.figure(figsize=(10,5))
variance = pca_full.explained_variance_ratio_
plt.figure(figsize=(10,5))
plt.plot(range(1, len(variance)+1), variance, marker='o')

plt.xlabel("Principal Component")
plt.ylabel("Explained Variance Ratio")

plt.title("Individual Explained Variance")

plt.grid()
plt.show()

# STEP 6: CUMULATIVE EXPLAINED VARIANCE
# ============================================================
# Cumulative variance shows total information retained
cumulative_variance = np.cumsum(variance)
plt.figure(figsize=(10,5))
plt.plot(
    range(1, len(cumulative_variance)+1),
    cumulative_variance,
    marker='o'
)

plt.axhline(y=0.90, linestyle='--', label="90% Variance")
plt.axhline(y=0.95, linestyle='--', label="95% Variance")

plt.xlabel("Number of Components")
plt.ylabel("Cumulative Explained Variance")

plt.title("PCA - Cumulative Explained Variance")

plt.legend()
plt.grid()
plt.show()

# Find components needed for 90% variance
components_90 = np.argmax(cumulative_variance >= 0.90) + 1
print("Components required for 90% variance:", components_90)

# STEP 7: IMAGE COMPRESSION USING PCA
# ============================================================
# Try different numbers of principal components
components = [5, 10, 20, 50, 100, 200]
plt.figure(figsize=(15,10))

for i, k in enumerate(components):

    # Create PCA model
    pca = PCA(n_components=k)

    # Compress the image
    reduced_image = pca.fit_transform(image)

    # Reconstruct the image
    reconstructed_image = pca.inverse_transform(reduced_image)

    # Display reconstructed image
    plt.subplot(2,3,i+1)

    plt.imshow(
        reconstructed_image,
        cmap='gray',
        vmin=0,
        vmax=255
    )

    plt.title(str(k) + " Components")

    plt.axis('off')

plt.suptitle("Image Reconstruction Using PCA", fontsize=16)

plt.tight_layout()
plt.show()

# STEP 8: COMPARE ORIGINAL AND COMPRESSED IMAGE
# ================================================
# Display original image
# Select 50 components
k = 50

pca = PCA(n_components=k)

reduced_image = pca.fit_transform(image)

reconstructed_image = pca.inverse_transform(reduced_image)

plt.figure(figsize=(12,5))

plt.subplot(1,2,1)

plt.imshow(image, cmap='gray')

plt.title("Original Image")

plt.axis('off')


plt.subplot(1,2,2)

plt.imshow(
    reconstructed_image,
    cmap='gray',
    vmin=0,
    vmax=255
)

plt.title("Compressed Image - 50 Components")

plt.axis('off')

plt.show()

# STEP 9: DISPLAY ORIGINAL VS RECONSTRUCTED PIXEL VALUES
# ============================================================
print("Original Pixel Values:")
print(image[:5, :5])
print("\nReconstructed Pixel Values:")
print(np.round(reconstructed_image[:5, :5], 2))

# STEP 10: CALCULATE RECONSTRUCTION ERROR
# ============================================================
# MSE measures the average squared difference
# between original and reconstructed pixels
mse = np.mean((image - reconstructed_image)**2)

# RMSE measures the square root of MSE

print("Mean Squared Error:", round(mse, 2))
print("Root Mean Squared Error:", round(rmse, 2))

rmse = np.sqrt(mse)

# STEP 11: CALCULATE COMPRESSION RATIO
# ============================================================
# Original image stores all pixel values
original_size = image.shape[0] * image.shape[1]
# PCA stores:
# 1. Reduced image representation
# 2. Principal component directions
# 3. Mean values

compressed_size = (
    image.shape[0] * k +
    k * image.shape[1] +
    image.shape[1]
)

compression_ratio = original_size / compressed_size
print("Original Values:", original_size)
print("Compressed Values:", compressed_size)
print("Compression Ratio:", round(compression_ratio, 2), ": 1")

# STEP 12: COMPONENTS VS RECONSTRUCTION ERROR
# ============================================================
component_list = [5, 10, 20, 50, 100, 200]
errors = []
for k in component_list:

    pca = PCA(n_components=k)

    reduced = pca.fit_transform(image)

    reconstructed = pca.inverse_transform(reduced)

    error = np.mean((image - reconstructed)**2)

    errors.append(error)

    # Plot reconstruction error

plt.figure(figsize=(9,5))
plt.plot(component_list, errors, marker='o')
plt.xlabel("Number of Components")
plt.ylabel("Mean Squared Error")
plt.title("Components vs Reconstruction Error")
plt.grid()
plt.show()

# STEP 13: COMPONENTS VS IMAGE QUALITY
# ============================================================
# Display image reconstruction for selected components

component_list = [5, 20, 50, 100, 200]
plt.figure(figsize=(15,8))
for i, k in enumerate(component_list):
    pca = PCA(n_components=k)
    reduced = pca.fit_transform(image)
    reconstructed = pca.inverse_transform(reduced)
    plt.subplot(1,5,i+1)
    plt.imshow(reconstructed, cmap='gray', vmin=0, vmax=255)
    plt.title("K = " + str(k))
    plt.axis('off')
plt.suptitle("Effect of Principal Components on Image Quality")
plt.tight_layout()
plt.show()

